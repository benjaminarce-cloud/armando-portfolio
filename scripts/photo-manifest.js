/**
 * Write lib/photo-manifest.ts from whatever scripts/prep-photos.sh produced.
 *
 * The whole-shoot folders come across as eighty-odd frames, and a project only
 * ever wants "every grad frame, in order". Hand-listing those slugs in
 * lib/projects.ts would be a page of noise that goes stale the moment a frame
 * is added or a duplicate is culled, so the slug list and each frame's true
 * shape are read back off the built files instead.
 *
 * build/media is gitignored, so the generated manifest is committed — it is the
 * only record of the shape of a photo that the site has at build time.
 *
 * Usage: node scripts/photo-manifest.js
 */

const fs = require("node:fs");
const path = require("node:path");
const { execFileSync } = require("node:child_process");

const ROOT = path.join(__dirname, "..");
const DIR = path.join(ROOT, "build", "media");
const OUT = path.join(ROOT, "lib", "photo-manifest.ts");

/**
 * Snap a measured ratio to the three the site actually lays out.
 *
 * The portrait boundary is the midpoint between 4:5 (0.800) and 2:3 (0.667),
 * so a frame lands in whichever box crops it least. It used to sit at 0.75,
 * which is exactly 3:4 — a real shape, and one that fell to the far side and
 * got cropped to 2:3 when 4:5 was the closer fit.
 */
function classify(width, height) {
  const v = width / height;
  if (v > 1.3) return "3:2";
  if (v > 0.733) return "4:5";
  return "2:3";
}

function main() {
  if (!fs.existsSync(DIR)) {
    console.error("No build/media. Run scripts/prep-photos.sh first.");
    process.exit(1);
  }

  const files = fs
    .readdirSync(DIR)
    .filter((f) => f.endsWith(".jpg"))
    // Posters belong to films, not to the photo index.
    .filter((f) => !f.endsWith("-poster.jpg"))
    .sort();

  const entries = files.map((file) => {
    const slug = path.basename(file, ".jpg");
    const size = execFileSync(
      "magick",
      ["identify", "-format", "%w %h", path.join(DIR, file)],
      { encoding: "utf8" }
    ).trim();
    const [w, h] = size.split(" ").map(Number);
    return { slug, ratio: classify(w, h) };
  });

  const body = entries
    .map((e) => `  "${e.slug}": "${e.ratio}",`)
    .join("\n");

  fs.writeFileSync(
    OUT,
    `// Generated by scripts/photo-manifest.js — do not edit by hand.
// Every still in build/media, with the shape it was actually delivered at.
// Regenerate after scripts/prep-photos.sh with: node scripts/photo-manifest.js

export type PhotoRatio = "4:5" | "2:3" | "3:2";

export const PHOTO_MANIFEST: Record<string, PhotoRatio> = {
${body}
};

/**
 * Every frame from one shoot, in the order prep-photos.sh wrote them — which
 * is the masters' own filename order, and so roughly the order they were shot.
 */
export const photosByPrefix = (prefix: string) =>
  Object.keys(PHOTO_MANIFEST)
    .filter((slug) => slug.startsWith(\`\${prefix}-\`))
    .sort();
`
  );

  console.log(`${entries.length} stills -> lib/photo-manifest.ts`);
}

main();
